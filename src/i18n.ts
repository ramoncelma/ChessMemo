const DICTS: Record<Lang, Dict> = { en, es, ca, fr, de };

export type TFn = (key: string, params?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
  return (key, params) => {
    let s = DICTS[lang][key] ?? en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        s = s.replace(`{${k}}`, String(v));
      }
    }
    return s;
  };
}

export const I18nContext = createContext<TFn>(makeT("en"));
export const useT = () => useContext(I18nContext);

// Level display helpers.
export function levelName(t: TFn, level: number): string {
  return level === 0 ? t("level.new") : t(`lvl.${level}.name`);
}
export function levelInterval(t: TFn, level: number): string {
  return level === 0 ? "" : t(`lvl.${level}.int`);
}
